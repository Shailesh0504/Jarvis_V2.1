_GLOBAL_SUGGESTION_MANAGER: Optional[SuggestionManager] = None
_GLOBAL_LOCK = threading.Lock()


def get_suggestion_manager() -> SuggestionManager:
    """Retrieves or creates the authoritative singleton SuggestionManager."""
    global _GLOBAL_SUGGESTION_MANAGER
    if _GLOBAL_SUGGESTION_MANAGER is None:
        with _GLOBAL_LOCK:
            if _GLOBAL_SUGGESTION_MANAGER is None:
                _GLOBAL_SUGGESTION_MANAGER = SuggestionManager()
    return _GLOBAL_SUGGESTION_MANAGER
