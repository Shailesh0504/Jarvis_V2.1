# core/intelligence/suggestion_manager.py
"""
Suggestion Manager and Cooldowns Engine for Jarvis V2.
Enforces global rate-limiting, per-pattern cooldowns, rejection backoff suppression,
and pending confirmation lifecycle management to ensure proactive suggestions are subtle,
respectful, and never intrusive.
"""

from collections import deque
import logging
import re
import threading
import time
from typing import Any, Dict, List, Optional, Tuple
import uuid

from .models import (
    ContextualSuggestion,
    ProactiveSuggestion,
    SuggestionCategory,
    SuggestionChip,
    SuggestionScore,
    SuggestionState,
    SuggestionUrgency,
)
from .pattern_engine import PatternLearningEngine
from core.capabilities import CapabilityRegistry

logger = logging.getLogger("jarvis.core.intelligence.suggestion")


class SuggestionManager:
    """
    Manages the presentation lifecycle, rate-limiting, cooldowns, and user feedback
    for proactive suggestions generated by Jarvis.
    """

    def __init__(
        self,
        pattern_engine: Optional[PatternLearningEngine] = None,
        min_global_cooldown_sec: float = 900.0,    # 15 minutes between proactive prompts
        min_pattern_cooldown_sec: float = 3600.0,   # 1 hour between identical pattern suggestions
        rejection_backoff_sec: float = 86400.0,     # 24 hours suppression on rejection
        confirmation_timeout_sec: float = 30.0,     # 30 seconds verbal response window
        max_history: int = 50
    ):
        self.pattern_engine = pattern_engine
        self.min_global_cooldown_sec = max(1.0, min_global_cooldown_sec)
        self.min_pattern_cooldown_sec = max(1.0, min_pattern_cooldown_sec)
        self.rejection_backoff_sec = max(1.0, rejection_backoff_sec)
        self.confirmation_timeout_sec = max(5.0, confirmation_timeout_sec)

        self._last_global_suggestion_time: float = 0.0
        self._pattern_last_presented: Dict[str, float] = {}
        self._pattern_last_rejected: Dict[str, float] = {}
        self._active_pending_suggestion: Optional[ProactiveSuggestion] = None
        self._history: deque = deque(maxlen=max_history)

        # Context-aware intelligent suggestion state
        self._goal_last_presented: Dict[str, float] = {}
        self._goal_last_rejected: Dict[str, float] = {}
        self._active_contextual_suggestion: Optional[ContextualSuggestion] = None
        self._contextual_history: deque = deque(maxlen=max_history)

        self._lock = threading.RLock()

    @staticmethod
    def get_suggestion_key(suggestion: ProactiveSuggestion) -> str:
        """Derives a canonical deduplication and cooldown key for a suggestion."""
        if suggestion.metadata and "pattern_key" in suggestion.metadata:
            return str(suggestion.metadata["pattern_key"])
        target_norm = (suggestion.target or "").lower().strip().replace(" ", "_")
        return f"{suggestion.intent}:{suggestion.action}:{target_norm}"

    def can_present_suggestion(
        self,
        suggestion: ProactiveSuggestion,
        current_time: Optional[float] = None
    ) -> Tuple[bool, str]:
        """
        Determines whether a candidate proactive suggestion is permitted to be presented.
        Evaluates rejection backoff, per-pattern cooldown, and global frequency capping.
        Returns (is_allowed, reason).
        """
        now = current_time if current_time is not None else time.time()
        key = self.get_suggestion_key(suggestion)

        with self._lock:
            # 1. Rejection Backoff: Suppress if user recently rejected this pattern
            if key in self._pattern_last_rejected:
                last_rejected = self._pattern_last_rejected[key]
                if (now - last_rejected) < self.rejection_backoff_sec:
                    remaining = int(self.rejection_backoff_sec - (now - last_rejected))
                    logger.debug("Suppressed '%s': under rejection backoff for %ds", key, remaining)
                    return False, f"Suppressed: User previously rejected this suggestion ({remaining}s backoff remaining)"

            # 2. Per-Pattern Cooldown: Do not suggest the same thing repeatedly
            if key in self._pattern_last_presented:
                last_presented = self._pattern_last_presented[key]
                if (now - last_presented) < self.min_pattern_cooldown_sec:
                    remaining = int(self.min_pattern_cooldown_sec - (now - last_presented))
                    logger.debug("Suppressed '%s': under per-pattern cooldown for %ds", key, remaining)
                    return False, f"Suppressed: Per-pattern cooldown active ({remaining}s remaining)"

            # 3. Global Cooldown: Rate-limit all proactive suggestions (unless HIGH urgency)
            if suggestion.urgency != SuggestionUrgency.HIGH and self._last_global_suggestion_time > 0.0:
                elapsed = now - self._last_global_suggestion_time
                if elapsed < self.min_global_cooldown_sec:
                    remaining = int(self.min_global_cooldown_sec - elapsed)
                    logger.debug("Suppressed '%s': under global cooldown for %ds", key, remaining)
                    return False, f"Suppressed: Global proactive cooldown active ({remaining}s remaining)"

            return True, "OK"

    def register_presented(
        self,
        suggestion: ProactiveSuggestion,
        current_time: Optional[float] = None
    ) -> None:
        """
        Registers that a suggestion has been presented to the user.
        Updates cooldown timers and sets the suggestion as actively pending confirmation.
        """
        now = current_time if current_time is not None else time.time()
        key = self.get_suggestion_key(suggestion)

        with self._lock:
            suggestion.state = SuggestionState.PROPOSED
            suggestion.created_at = now
            self._last_global_suggestion_time = now
            self._pattern_last_presented[key] = now
            self._active_pending_suggestion = suggestion
            self._history.append(suggestion)
            logger.info(
                "Proactive suggestion presented: [%s] target='%s' (id=%s)",
                suggestion.intent, suggestion.target, suggestion.suggestion_id
            )

    def get_pending_suggestion(
        self,
        current_time: Optional[float] = None
    ) -> Optional[ProactiveSuggestion]:
        """
        Retrieves the currently active suggestion awaiting confirmation.
        Automatically marks it EXPIRED and clears it if the confirmation window has elapsed.
        """
        now = current_time if current_time is not None else time.time()

        with self._lock:
            if not self._active_pending_suggestion:
                return None

            elapsed = now - self._active_pending_suggestion.created_at
            if elapsed > self.confirmation_timeout_sec:
                logger.debug(
                    "Pending suggestion '%s' expired after %.1fs",
                    self._active_pending_suggestion.suggestion_id, elapsed
                )
                self._active_pending_suggestion.state = SuggestionState.EXPIRED
                self._active_pending_suggestion = None
                return None

            return self._active_pending_suggestion

    def record_feedback(
        self,
        suggestion_id: str,
        accepted: bool,
        current_time: Optional[float] = None
    ) -> Optional[ProactiveSuggestion]:
        """
        Records user verbal/text feedback on a proposed suggestion.
        If accepted: marks ACCEPTED and reinforces pattern confidence.
        If rejected: marks REJECTED, enters 24h backoff, and penalizes pattern confidence.
        """
        now = current_time if current_time is not None else time.time()

        with self._lock:
            target_sug: Optional[ProactiveSuggestion] = None

            if self._active_pending_suggestion and self._active_pending_suggestion.suggestion_id == suggestion_id:
                target_sug = self._active_pending_suggestion
                self._active_pending_suggestion = None
            else:
                for s in reversed(self._history):
                    if s.suggestion_id == suggestion_id:
                        target_sug = s
                        break

            # Also check if this feedback applies to active contextual suggestion
            if self._active_contextual_suggestion and self._active_contextual_suggestion.suggestion_id == suggestion_id:
                ctx_sug = self._active_contextual_suggestion
                self._active_contextual_suggestion = None
                g = ctx_sug.goal
                if accepted:
                    self._goal_last_rejected.pop(g, None)
                    logger.info("User ACCEPTED contextual suggestion for goal '%s' (%s)", g, suggestion_id)
                else:
                    self._goal_last_rejected[g] = now
                    logger.info("User REJECTED contextual suggestion for goal '%s' (%s). Backoff activated.", g, suggestion_id)
                return None

            if not target_sug:
                for cs in reversed(self._contextual_history):
                    if cs.suggestion_id == suggestion_id:
                        g = cs.goal
                        if accepted:
                            self._goal_last_rejected.pop(g, None)
                        else:
                            self._goal_last_rejected[g] = now
                        return None
                logger.warning("Feedback received for unknown suggestion_id='%s'", suggestion_id)
                return None

            key = self.get_suggestion_key(target_sug)

            if accepted:
                target_sug.state = SuggestionState.ACCEPTED
                logger.info("User ACCEPTED suggestion '%s' (%s)", target_sug.target, key)
                # Clear any lingering rejection penalty on this pattern
                self._pattern_last_rejected.pop(key, None)
            else:
                target_sug.state = SuggestionState.REJECTED
                self._pattern_last_rejected[key] = now
                logger.info(
                    "User REJECTED suggestion '%s' (%s). Backoff activated for %ds",
                    target_sug.target, key, self.rejection_backoff_sec
                )
                # Apply penalty in pattern engine if available
                if self.pattern_engine and target_sug.metadata.get("pattern_key"):
                    p_key = target_sug.metadata["pattern_key"]
                    pat = self.pattern_engine.get_pattern(p_key)
                    if pat:
                        pat.confidence = max(0.20, round(pat.confidence - 0.15, 2))
                        logger.debug("Penalized confidence for '%s' to %.2f", p_key, pat.confidence)

            return target_sug

    def clear_pending(self) -> None:
        """Manually clears the active pending suggestion."""
        with self._lock:
            self._active_pending_suggestion = None
            self._active_contextual_suggestion = None

    def get_history(self) -> List[ProactiveSuggestion]:
        """Returns a snapshot copy of recently presented suggestions."""
        with self._lock:
            return list(self._history)

    def evaluate_conversational_suggestion(
        self,
        user_input: str,
        answer: str,
        source: str = "cli",
        active_context: Optional[Any] = None,
        current_time: Optional[float] = None,
    ) -> Optional[ContextualSuggestion]:
        """
        Evaluates whether a conversational next-step suggestion should accompany an answer.
        Pipeline:
        USER QUESTION -> USER INTENT -> USER GOAL -> ANSWER -> WHAT WOULD BE USEFUL NEXT? -> OPTIONAL RELEVANT SUGGESTION

        Returns ContextualSuggestion if decision is SUGGEST and score >= 0.75, else None.
        Internal debug representation is logged per Section 20 requirements.
        """
        now = current_time if current_time is not None else time.time()
        raw_text = (user_input or "").strip()
        raw_ans = (answer or "").strip()

        if not raw_text or not raw_ans:
            return None

        # 1. Negative Suppression: If the answer already asks a question / requests slot input
        if raw_ans.endswith("?") or any(
            q_word in raw_ans.lower()
            for q_word in ["kaunsa", "kaunsi", "bataiye", "batayein", "which one", "what would you"]
        ):
            return None

        # 2. Negative Suppression: Errors, refusals, unhandled input
        ans_low = raw_ans.lower()
        if any(err_word in ans_low for err_word in [
            "error", "failed", "unsupported", "samajh nahi aayi", "nahi kar sakta",
            "capabilities mein nahi hai", "permission denied"
        ]):
            return None

        inp_low = raw_text.lower()
        clean_inp = re.sub(r"[^\w\s]", " ", inp_low).strip()
        clean_inp = re.sub(r"\s+", " ", clean_inp)

        # 3. Negative Suppression: Greetings, casual small-talk, gratitude
        if re.match(
            r"^(?:hello|hi|hey|good\s+morning|good\s+evening|good\s+afternoon|good\s+night|namaste|kaise\s+ho|kya\s+haal|thank\s+you|thanks|shukriya|dhanyawad)\b",
            clean_inp
        ):
            return None

        # 4. Negative Suppression: Pure static factual Q&A / static GK / simple calculations
        if (
            re.match(r"^\d+\s*[\+\-\*\/]\s*\d+", clean_inp)
            or re.search(r"\b(?:kitna\s+hota\s+hai|calculate|plus|minus|multiply|divided\s+by)\b", clean_inp)
            or re.search(r"\b(?:capital|rajdhani|currency|mudra|president|pradhan\s*mantri|pm|invented|discover|formula\s+of|symbol\s+of|atomic\s+number|full\s+form|meaning\s+of|definition\s+of)\b", clean_inp)
        ):
            return None

        # 5. Negative Suppression: Simple completed commands (launch app, volume, minimize, recycle bin, power)
        # These commands must execute and STOP immediately without any suggestions.
        if (
            re.match(r"^(?:open|launch|kholo|start|run)\s+[a-z0-9_\-\s]+$", clean_inp)
            or re.search(r"\b(?:chrome|notepad|calculator|word|excel|powerpoint|vlc|spotify|settings|file\s+explorer|browser)\s+(?:kholo|open\s+karo|launch\s+karo|chalao)\b", clean_inp)
            or re.search(r"\b(?:set\s+volume|volume\s+\d+|volume\s+badhao|volume\s+kam|mute|unmute|awaaz\s+badhao|sound\s+kam)\b", clean_inp)
            or re.search(r"\b(?:brightness|screen\s+bright)\b", clean_inp)
            or re.search(r"\b(?:minimize|maximize|chhota\s+karo|bada\s+karo)\b", clean_inp)
            or re.search(r"\b(?:recycle\s*bin|trash)\s+(?:empty|clean|saaf|khali)\b", clean_inp)
            or re.search(r"\b(?:lock\s+system|system\s+lock|lock\s+screen|pc\s+lock|lock\s+karo)\b", clean_inp)
            or re.search(r"\b(?:shutdown|restart|reboot|turn\s+off)\b", clean_inp)
            or re.search(r"\b(?:screenshot|screen\s+capture)\b", clean_inp)
        ):
            return None

        # 6. Domain Goal Identification & Next-Step Mapping
        goal: Optional[str] = None
        intent: str = "conversational_advice"
        sug_text: str = ""
        action_name: Optional[str] = None
        target_name: Optional[str] = None
        target_plug: Optional[str] = None
        cap_id: Optional[str] = None
        category: SuggestionCategory = SuggestionCategory.NEXT_STEP

        # A. Travel Planning
        if any(w in clean_inp for w in ["jana hai", "travel to", "how to go", "kaise jaaun", "kaise jaye", "trip to", "flights to", "trains to", "route to"]):
            goal = "TRAVEL_PLANNING"
            category = SuggestionCategory.NEXT_STEP
            action_name = "compare_travel_routes"
            cap_id = "browser.web_search"
            target_plug = "browser"

            dest_match = re.search(r"\bmujhe\s+([a-z]+)\s+jana\b", clean_inp)
            if not dest_match:
                dest_match = re.search(r"\b([a-z]+)\s+jana\s+hai\b", clean_inp)
            if not dest_match:
                dest_match = re.search(r"\b(?:to|for)\s+([a-z]+)\b", clean_inp)
            destination = dest_match.group(1).title() if dest_match else ""
            if destination.lower() in ("mujhe", "hume", "kaise", "ghar"):
                destination = ""
            target_name = destination or "destination"
            sug_text = "Kya main dono routes compare karke dikhaun ya ticket booking site kholun?"

        # B. Weather Forecast & Planning
        elif any(w in clean_inp for w in ["weather kaisa hai", "mausam kaisa hai", "weather in", "temperature in", "barish hogi kya", "mausam kaisa"]):
            goal = "WEATHER_CHECK"
            category = SuggestionCategory.RELEVANT_INFORMATION
            action_name = "get_hourly_forecast"
            cap_id = "weather.forecast.query"
            target_plug = "weather"

            city_match = re.search(r"\bin\s+([a-z]+)\b", clean_inp)
            if not city_match:
                city_match = re.search(r"\b([a-z]+)\s+mein\b", clean_inp)
            city = city_match.group(1).title() if city_match else ""
            if city.lower() in ("aaj", "kal", "weather", "mausam", "kaisa"):
                city = ""
            target_name = city or "local"
            sug_text = "Kya aap agle 6 ghante ka hourly forecast ya rain alert dekhna chahenge?"

        # C. IT Troubleshooting
        elif any(w in clean_inp for w in ["rdp", "remote desktop", "port 3389", "connect nahi ho raha", "network unreachable", "ping nahi aa raha", "wifi connect nahi ho raha", "blue screen", "bsod"]) and any(w in clean_inp for w in ["kyun", "kaise", "kya karu", "issue", "problem", "solve", "fix", "nahi ho raha", "error"]):
            goal = "IT_TROUBLESHOOTING"
            category = SuggestionCategory.NEXT_STEP
            action_name = "start_troubleshooting_checklist"
            cap_id = "it.infrastructure.troubleshoot"
            target_plug = "it_knowledge"
            target_name = "rdp" if "rdp" in clean_inp else "network"
            sug_text = "Kya main step-by-step troubleshooting checklist batana shuru karun?"

        # D. DNS Setup & Guide
        elif any(w in clean_inp for w in ["dns kya hai", "what is dns", "dns kaise setup", "dns configure", "dns change", "flush dns"]):
            goal = "DNS_EXPLANATION_OR_SETUP"
            category = SuggestionCategory.USEFUL_ACTION
            action_name = "show_dns_setup_guide"
            cap_id = "system.network.configuration"
            target_plug = "system"
            target_name = "dns"
            sug_text = "Kya aap apne computer mein DNS server configure ya flush karne ke practical steps dekhna chahenge?"

        # E. Excel Duplicate Removal & Formulas
        elif ("excel" in clean_inp and any(w in clean_inp for w in ["duplicate", "vlookup", "formula"])) or "duplicate entries kaise" in clean_inp:
            goal = "EXCEL_DUPLICATE_REMOVAL"
            category = SuggestionCategory.USEFUL_ACTION
            action_name = "show_excel_formula_example"
            cap_id = "office.excel.operations"
            target_plug = "excel"
            target_name = "excel"
            sug_text = "Kya main iska exact COUNTIF formula example dikhaun ya Excel Remove Duplicates tool ke steps bataun?"

        # F. Music Desire (Expressed Desire)
        elif any(w in clean_inp for w in ["gaana sunne ka mann", "song sunne ka mann", "kuch accha sunao", "play some music", "mood kharab hai koi gaana"]):
            goal = "MUSIC_DESIRE"
            category = SuggestionCategory.ALTERNATIVE
            action_name = "play_trending_songs"
            cap_id = "media.youtube.play"
            target_plug = "youtube"
            target_name = "music"
            sug_text = "Aapka favorite genre play karun ya trending romantic songs chalaun?"

        # G. System Cleanup & Performance
        elif any(w in clean_inp for w in ["computer ko thoda clean", "pc slow chal raha hai", "laptop hang", "system clean kaise", "temporary files clean"]):
            goal = "SYSTEM_CLEANUP"
            category = SuggestionCategory.USEFUL_ACTION
            action_name = "open_disk_cleanup"
            cap_id = "system.maintenance.temp_cleanup"
            target_plug = "system"
            target_name = "cleanmgr"
            sug_text = "Kya main safe temporary files cleanup utility open karun ya disk cleanup launch karun?"

        # H. Backup Planning
        elif any(w in clean_inp for w in ["backup kaise", "files ka backup", "data backup planning", "system backup kaise"]):
            goal = "BACKUP_PLANNING"
            category = SuggestionCategory.NEXT_STEP
            action_name = "show_backup_options"
            cap_id = "system.backup.management"
            target_plug = "system"
            target_name = "backup"
            sug_text = "Kya main automated backup options aur folder selection checklist dikhaun?"

        # I. Equity Research & Stock Market
        elif any(w in clean_inp for w in ["share market", "stock idea", "equity research", "swing trade", "1 month investment", "stock shortlist"]):
            goal = "EQUITY_RESEARCH"
            category = SuggestionCategory.NEXT_STEP
            action_name = "show_equity_shortlist"
            cap_id = "finance.equity_research"
            target_plug = "equity_research"
            target_name = "equity"
            sug_text = "Kya aap short-term candidates ka risk scenario aur technical breakdown dekhna chahenge?"

        # If no recognized goal matches, suppress
        if not goal:
            return None

        # 7. Capability Availability Gate
        is_unsupported, _ = CapabilityRegistry.is_unsupported_operation(raw_text, goal)
        cap_avail = False
        if not is_unsupported and cap_id:
            cap_avail = CapabilityRegistry.is_available(cap_id)

        # 8. Repetition & Cooldown Penalty
        rep_penalty = 0.0
        with self._lock:
            if goal in self._goal_last_rejected:
                last_rej = self._goal_last_rejected[goal]
                if (now - last_rej) < self.rejection_backoff_sec:
                    rep_penalty = 0.50
            elif goal in self._goal_last_presented:
                last_pres = self._goal_last_presented[goal]
                if (now - last_pres) < 300.0:  # 5 minutes goal cooldown
                    rep_penalty = 0.35

        # 9. SuggestionScore Calculation
        score = SuggestionScore(
            goal_alignment=1.0,
            context_alignment=0.90,
            capability_match=1.0 if cap_avail else 0.0,
            confidence=0.95,
            usefulness=0.90,
            repetition_penalty=rep_penalty,
        )

        decision = "SUGGEST" if (score.total >= 0.75 and cap_avail) else "SUPPRESS"

        candidate = ContextualSuggestion(
            suggestion_id=str(uuid.uuid4())[:8],
            category=category,
            goal=goal,
            intent=intent,
            text=sug_text,
            action=action_name,
            target=target_name,
            target_plugin=target_plug,
            capability_id=cap_id,
            capability_available=cap_avail,
            score=score,
            decision=decision,
            created_at=now,
        )

        # 10. Internal Telemetry & Debug Log (Section 20)
        logger.info(
            "\nUSER: %s\nGOAL: %s\nANSWER: %s\nSUGGESTION: %s\nCAPABILITY: %s\nSCORE: %.2f\nDECISION: %s",
            raw_text,
            goal,
            (raw_ans[:60] + "...") if len(raw_ans) > 60 else raw_ans,
            sug_text,
            "AVAILABLE" if cap_avail else "UNAVAILABLE",
            score.total,
            decision,
        )

        if decision == "SUGGEST":
            with self._lock:
                self._goal_last_presented[goal] = now
                self._active_contextual_suggestion = candidate
                self._contextual_history.append(candidate)
            return candidate

        return None

    def generate_contextual_chips(
        self,
        active_context: Optional[Any] = None,
        dialog_manager: Optional[Any] = None,
        last_user_input: str = "",
        last_assistant_response: str = "",
        system_state: Optional[Dict[str, Any]] = None,
        limit: int = 5,
        current_time: Optional[float] = None,
    ) -> List[SuggestionChip]:
        """
        Generates context-aware, goal-aligned, capability-filtered suggestion chips for the UI.
        Enforces Rule 1.1 Invariant: Single Source of Truth for suggestions.

        Decides 'WHAT WOULD BE USEFUL NEXT?' based on:
        1. Pending Slot Filling & Confirmations (Priority 1)
        2. Negative Suppression: Zero suggestions for pure factual Q&A / calculations / greetings
        3. Active User Goals & Conversational Troubleshooting (RDP, Network, Travel, Music, Cleanup)
        4. Active Application Context (Chrome, Excel, File Explorer, VLC)
        5. Redundancy Suppression (never suggest an already active app/website/state)
        6. Capability Verification (never suggest unsupported actions)
        7. Relevance Scoring & Top 3-5 Capping
        """
        now = current_time if current_time is not None else time.time()
        user_inp = (last_user_input or "").strip()
        asst_ans = (last_assistant_response or "").strip()
        state = dict(system_state or {})

        inp_low = user_inp.lower()
        clean_inp = re.sub(r"[^\w\s]", " ", inp_low).strip()
        clean_inp = re.sub(r"\s+", " ", clean_inp)
        ans_low = asst_ans.lower()

        # =====================================================================
        # STAGE 1: PENDING SLOT FILLING & CONFIRMATIONS (PRIORITY 1)
        # =====================================================================
        # A. Pending System Action / Confirmation
        if dialog_manager:
            has_pending_conf = False
            if hasattr(dialog_manager, "confirmation_manager") and dialog_manager.confirmation_manager:
                if dialog_manager.confirmation_manager.has_pending_confirmation():
                    has_pending_conf = True
            elif hasattr(dialog_manager, "has_pending_system_action") and dialog_manager.has_pending_system_action():
                has_pending_conf = True
            elif getattr(dialog_manager, "pending_system_action", None):
                has_pending_conf = True

            if has_pending_conf:
                return [
                    SuggestionChip(
                        label="Haan, kar do",
                        command="haan",
                        category="confirmation",
                        target="system",
                        score=1.0,
                    ),
                    SuggestionChip(
                        label="Nahi, cancel karo",
                        command="nahi",
                        category="confirmation",
                        target="system",
                        score=0.99,
                    ),
                ]

        # B. DialogManager Active Lock / Missing Slots
        if dialog_manager and hasattr(dialog_manager, "active_lock") and dialog_manager.active_lock:
            lock = dialog_manager.active_lock
